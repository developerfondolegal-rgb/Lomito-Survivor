// Razas jugables que usan estos sprites (id de src/razas.js -> sprite de arriba)
const RAZAS_SPRITE_DE = { quiltro: 'quiltro', pitbull: 'pitbull', galgo: 'galgo', beagle: 'beagle', chowchow: 'chowchow' };
const RAZAS_SPRITE_ESCALA = 2;    // 32 x 32 agrandado 2 veces = 64 x 64 px en pantalla (nítido)
const RAZAS_SPRITE_ANIMS = [      // nombre, cuadros por segundo, se repite
  ['idle', 6, -1],
  ['correr', 12, -1],
  ['dano', 1, 0],
  ['ataque', 12, 0]
];

// Clave de la textura de una raza ('raza_quiltro'), o null si no tiene sprite nuevo
function claveSpriteRaza(razaId) {
  const id = RAZAS_SPRITE_DE[razaId];
  return id && RAZAS_SPRITES[id] ? 'raza_' + id : null;
}

// "#rrggbb" o "#rrggbbaa" -> [r, g, b, a]
function colorSpriteRaza(hex) {
  const h = hex.replace('#', '');
  const n = (i) => parseInt(h.slice(i, i + 2), 16);
  return [n(0), n(2), n(4), h.length >= 8 ? n(6) : 255];
}

// Crea (solo la primera vez) la textura de cada raza con SU paleta, con todos
// los cuadros uno al lado del otro, y sus animaciones: raza_quiltro_idle, _correr, _dano, _ataque
function crearSpritesRazas(escena) {
  Object.keys(RAZAS_SPRITES).forEach((id) => {
    const datos = RAZAS_SPRITES[id];
    const clave = 'raza_' + id;
    const cuadros = [];
    const indices = {};
    RAZAS_SPRITE_ANIMS.forEach(([nombre]) => {
      indices[nombre] = [];
      (datos.anims[nombre] || []).forEach((filas) => { indices[nombre].push(cuadros.length); cuadros.push(filas); });
    });
    if (!escena.textures.exists(clave)) {
      const lado = 32;
      const textura = escena.textures.createCanvas(clave, lado * cuadros.length, lado);
      const ctx = textura.getContext();
      const imagen = ctx.createImageData(lado * cuadros.length, lado);
      const colores = {};
      Object.keys(datos.paleta).forEach((letra) => { colores[letra] = colorSpriteRaza(datos.paleta[letra]); });
      cuadros.forEach((filas, n) => {
        filas.forEach((fila, y) => {
          for (let x = 0; x < fila.length; x++) {
            const c = colores[fila[x]];
            if (!c) continue;  // '.' (o una letra sin color) = transparente
            const k = (y * lado * cuadros.length + n * lado + x) * 4;
            imagen.data[k] = c[0]; imagen.data[k + 1] = c[1]; imagen.data[k + 2] = c[2]; imagen.data[k + 3] = c[3];
          }
        });
        textura.add(n, 0, n * lado, 0, lado, lado);
      });
      ctx.putImageData(imagen, 0, 0);
      textura.refresh();
    }
    RAZAS_SPRITE_ANIMS.forEach(([nombre, fps, repetir]) => {
      const anim = clave + '_' + nombre;
      if (escena.anims.exists(anim) || indices[nombre].length === 0) return;
      escena.anims.create({ key: anim, frames: indices[nombre].map((i) => ({ key: clave, frame: i })), frameRate: fps, repeat: repetir });
    });
  });
}

// Elige la animación del perro del jugador: daño > ataque > correr > quieto,
// y lo da vuelta hacia donde va (el dibujo mira a la derecha)
function animarPerroRaza(perro, vx, vy, dano, ataque) {
  const clave = perro.texture.key;
  let nombre = 'idle';
  if (dano) nombre = 'dano';
  else if (ataque) nombre = 'ataque';
  else if (vx * vx + vy * vy > 25) nombre = 'correr';
  if (vx < -5) perro.setFlipX(true);
  else if (vx > 5) perro.setFlipX(false);
  const anim = clave + '_' + nombre;
  if (perro.anims.currentAnim && perro.anims.currentAnim.key === anim) return;
  if (nombre === 'dano' || nombre === 'ataque') perro.anims.play(anim);
  else perro.anims.play(anim, true);
}
